"""Generate docs/NUMERICAL_EXAMPLES.md from the engine (run: python docs/make_numerical_examples.py).

tests/test_docs.py regenerates the text and checks it equals the committed file, so every number in the document
is reproducible from the code.
"""
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from core import priors as P  # noqa: E402
from core import walkthrough as W  # noqa: E402
from core.data import walkthrough_dataset  # noqa: E402
from core.quadrature import moments  # noqa: E402

OUT = ROOT / "docs" / "NUMERICAL_EXAMPLES.md"


def md(frame, digits=6):
    cols = list(frame.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in frame.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, (float, np.floating)):
                cells.append(f"{v:.{digits}f}" if abs(v) >= 1e-4 or v == 0 else f"{v:.6e}")
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def build():
    d = walkthrough_dataset()
    lines = ["# Numerical examples (engine-generated)", "",
             "Generated by `python docs/make_numerical_examples.py` from `core.walkthrough` / `core.em`. "
             "`tests/test_docs.py` fails if this file no longer matches the engine.", "",
             "## Example 1 · PCM, fixed normal prior, three-point Gauss–Hermite", "",
             "Data (5 examinees × 3 items, categories 0–2):", "", md(W.table_responses(d), 0), "",
             "Starting values: δ = (−0.5, 0.5) for every item. Prior: θ = (−√3, 0, √3), π = (1/6, 2/3, 1/6).", ""]
    cfg = W.walkthrough_config("PCM", "fixed_normal")
    items = W.default_start(d, "PCM")
    for t in range(1, 4):
        cyc = W.cycle(d, cfg, items)
        lines += [f"### Cycle {t}", ""]
        if t == 1:
            lines += ["Category probabilities P_jk(θ_q):", "", md(W.table_category_probs(items, cyc["nodes"])), "",
                      "Likelihood, unnormalised and normalised posterior:", "",
                      md(W.table_posterior(d, cyc)), "",
                      "Expected counts C_jkq:", "", md(W.table_counts(d, cyc)), ""]
        rows = []
        for a, b in zip(cyc["items"], cyc["new_items"]):
            rows.append(dict(item=a.id, d1_before=a.d[0], d2_before=a.d[1], d1_after=b.d[0], d2_after=b.d[1]))
        import pandas as pd
        lines += ["M-step (each item's steps maximise Σ_qk C log P):", "", md(pd.DataFrame(rows)), "",
                  f"Marginal log-likelihood: {cyc['ll_before']:.10f} → {cyc['ll_after']:.10f} "
                  f"(largest item change {cyc['item_change']:.6e}).", ""]
        items = cyc["new_items"]
    lines += ["## Example 2 · Constrained empirical update (dual Newton)", ""]
    x = np.linspace(-3, 3, 7)
    n = np.array([2.0, 6.0, 14.0, 20.0, 9.0, 6.0, 3.0])
    w0 = P.empirical_unconstrained(n)
    w1, info1 = P.empirical_constrained(n, x, 0.0, None)
    w2, info2 = P.empirical_constrained(n, x, 0.0, 1.0)
    import pandas as pd
    lines += ["Posterior node masses n_q on θ = −3, −2, …, 3:", "",
              md(pd.DataFrame(dict(theta=x, n=n, unconstrained=w0, mean_0=w1, mean_0_sd_1=w2))), "",
              f"Moments — unconstrained: mean {moments(x, w0)[0]:.6f}, SD {moments(x, w0)[1]:.6f}; "
              f"mean-constrained: mean {moments(x, w1)[0]:.2e}, SD {moments(x, w1)[1]:.6f} (λ = "
              f"{np.round(info1['lagrange'], 6).tolist()}); mean- and SD-constrained: mean {moments(x, w2)[0]:.2e}, "
              f"SD {moments(x, w2)[1]:.10f} (λ = {np.round(info2['lagrange'], 6).tolist()}).", "",
              f"Q_prior: unconstrained {P.objective(n, w0):.6f} ≥ mean-constrained {P.objective(n, w1):.6f} ≥ "
              f"both {P.objective(n, w2):.6f} — each added constraint can only lower the maximum.", "",
              "## Example 3 · GPCM with an estimated empirical prior on three nodes", "",
              "With θ = (−√3, 0, √3) and the reference mean 0 and variance 1 both fixed (slopes are estimated), "
              "Σπ = 1, Σπθ = 0 and Σπθ² = 1 leave no freedom: the masses stay (1/6, 2/3, 1/6) whatever the posterior.", ""]
    c3 = W.cycle(d, W.walkthrough_config("GPCM", "estimated_empirical"), W.default_start(d, "GPCM"))
    lines += [md(pd.DataFrame(dict(theta=c3["nodes"][0], before=c3["weights"][0], average_posterior=c3["n_g"][0] / d.N,
                                   after=c3["new_weights"][0]))), ""]
    c4 = W.cycle(d, W.walkthrough_config("PCM", "estimated_empirical"), W.default_start(d, "PCM"))
    lines += ["For the PCM only the mean is fixed (the slope fixes the unit), leaving one degree of freedom:", "",
              md(pd.DataFrame(dict(theta=c4["nodes"][0], before=c4["weights"][0], average_posterior=c4["n_g"][0] / d.N,
                                   after=c4["new_weights"][0]))), ""]
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(build())
    print(OUT.read_text()[:3000])
