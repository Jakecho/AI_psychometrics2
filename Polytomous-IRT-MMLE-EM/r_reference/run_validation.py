"""Execute every reference case and write docs/VALIDATION_RESULTS.md plus docs/validation_record.json.

Run: python -m r_reference.run_validation. The JSON record is what page 12 shows as the recorded local run
(useful where R is unavailable, e.g. Streamlit Community Cloud). It is never edited by hand.
"""
import json
from dataclasses import replace
from datetime import date
from pathlib import Path

from core.em import DESIGN_NAMES, fit
from core.priors import PRIOR_NAMES
from core.simulation import simulate
from r_reference.bridge import check_r, compare, run_reference
from r_reference.cases import CASES, DIFFERENCES, TIGHT

DOCS = Path(__file__).resolve().parents[1] / "docs"
OUT = DOCS / "VALIDATION_RESULTS.md"
RECORD = DOCS / "validation_record.json"


def run_case(pkg, spec, cfg, note, kind):
    d = simulate(spec)
    cfg = replace(cfg, **TIGHT)
    res = fit(d, cfg)
    ref = run_reference(pkg, d, cfg)
    label = (f"{cfg.model} · {DESIGN_NAMES[cfg.design]} · {PRIOR_NAMES[cfg.prior]}"
             + (f" · {cfg.fipc_method}" if cfg.anchored else "")
             + (f" · normal={cfg.normal_update}" if cfg.prior == "estimated_normal" else "")
             + (f" · hist={cfg.empirical_update}" if cfg.prior == "estimated_empirical" else ""))
    out = dict(kind=kind, package=pkg, setup=label, status=ref["status"], note=note,
               lab_cycles=res.cycles, lab_converged=bool(res.converged))
    if ref["status"] != "Executed":
        out["reason"] = ref.get("reason", "")
        return out
    _, _, sm = compare(res, ref)
    out.update(version=ref.get("version"), call=ref.get("call"), max_item_diff=sm["max_item_diff"],
               max_moment_diff=sm["max_moment_diff"], loglik_lab=sm["loglik_lab"], loglik_ref=sm["loglik_ref"],
               max_density_TV=sm["max_density_TV"])
    return out


def md_row(r):
    if r["status"] != "Executed":
        return f"| {r['package']} | {r['setup']} | {r['status']}: {r.get('reason', '')[:80]} | | | | {r['note']} |"
    tv = "—" if r["max_density_TV"] is None else f"{r['max_density_TV']:.1e}"
    return (f"| {r['package']} {r['version']} | {r['setup']} | {r['max_item_diff']:.1e} | {r['max_moment_diff']:.1e} | "
            f"{r['loglik_lab']:.4f} / {r['loglik_ref']:.4f} | {tv} | {r['note']} |")


def main():
    info = check_r()
    rows = [run_case(p, s, c, f"agreement asserted < {tol:g}", "agreement") for p, s, c, tol in CASES]
    rows += [run_case(p, s, c, note, "difference") for p, s, c, note in DIFFERENCES]
    grid = f"{CASES[0][2].n_nodes} equally spaced nodes on ±{CASES[0][2].bound:g}"
    record = dict(date=date.today().isoformat(), environment={k: info.get(k) for k in ("R", "TAM", "irtQ", "mirt")},
                  grid=grid, D=1, lab_tolerances=TIGHT, rows=rows)
    RECORD.write_text(json.dumps(record, indent=2, default=float) + "\n")
    head = "| Package | Set-up | max item diff | max moment diff | ℓ lab / ref | density TV | note |\n|---|---|---|---|---|---|---|"
    lines = [f"# Executed reference validation ({record['date']})", "",
             f"Environment: {info.get('R', 'R unavailable')} · TAM {info.get('TAM')} · irtQ {info.get('irtQ')} · "
             f"mirt {info.get('mirt')}. Grid: {grid}, D = 1, lab tolerances {TIGHT}. Generated by "
             "`python -m r_reference.run_validation` (structured copy: `validation_record.json`).", "", head]
    lines += [md_row(r) for r in rows if r["kind"] == "agreement"]
    lines += ["", "## Documented differences (not asserted)", "", head]
    lines += [md_row(r) for r in rows if r["kind"] == "difference"]
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
