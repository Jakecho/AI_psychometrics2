"""Execute every reference case and write docs/VALIDATION_RESULTS.md (run: python -m r_reference.run_validation)."""
from dataclasses import replace
from datetime import date
from pathlib import Path

from core.em import DESIGN_NAMES, fit
from core.priors import PRIOR_NAMES
from core.simulation import simulate
from r_reference.bridge import check_r, compare, run_reference
from r_reference.cases import CASES, DIFFERENCES, TIGHT

OUT = Path(__file__).resolve().parents[1] / "docs" / "VALIDATION_RESULTS.md"


def row(pkg, spec, cfg, note):
    d = simulate(spec)
    cfg = replace(cfg, **TIGHT)
    res = fit(d, cfg)
    ref = run_reference(pkg, d, cfg)
    label = (f"{cfg.model} · {DESIGN_NAMES[cfg.design]} · {PRIOR_NAMES[cfg.prior]}"
             + (f" · {cfg.fipc_method}" if cfg.anchored else "")
             + (f" · normal={cfg.normal_update}" if cfg.prior == "estimated_normal" else "")
             + (f" · hist={cfg.empirical_update}" if cfg.prior == "estimated_empirical" else ""))
    if ref["status"] != "Executed":
        return f"| {pkg} | {label} | {ref['status']}: {ref.get('reason', '')[:80]} | | | | {note} |"
    _, _, sm = compare(res, ref)
    tv = "—" if sm["max_density_TV"] is None else f"{sm['max_density_TV']:.1e}"
    return (f"| {pkg} {ref.get('version')} | {label} | {sm['max_item_diff']:.1e} | {sm['max_moment_diff']:.1e} | "
            f"{sm['loglik_lab']:.4f} / {sm['loglik_ref']:.4f} | {tv} | {note} |")


def main():
    info = check_r()
    lines = [f"# Executed reference validation ({date.today().isoformat()})", "",
             f"Environment: {info.get('R', 'R unavailable')} · TAM {info.get('TAM')} · irtQ {info.get('irtQ')} · "
             f"mirt {info.get('mirt')}. Grid: {CASES[0][2].n_nodes} equally spaced nodes on ±{CASES[0][2].bound:g}, "
             f"D = 1, lab tolerances {TIGHT}. Generated by `python -m r_reference.run_validation`.", "",
             "| Package | Set-up | max item diff | max moment diff | ℓ lab / ref | density TV | note |",
             "|---|---|---|---|---|---|---|"]
    for pkg, spec, cfg, tol in CASES:
        lines.append(row(pkg, spec, cfg, f"agreement asserted < {tol:g}"))
    lines += ["", "## Documented differences (not asserted)", "",
              "| Package | Set-up | max item diff | max moment diff | ℓ lab / ref | density TV | note |",
              "|---|---|---|---|---|---|---|"]
    for pkg, spec, cfg, note in DIFFERENCES:
        lines.append(row(pkg, spec, cfg, note))
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
